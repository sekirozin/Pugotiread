import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import net from 'node:net';
import { spawn } from 'node:child_process';
import { PDFDocument } from 'pdf-lib';

test('RPG: templates, modules, private copies, owner sharing, readonly viewers, rename persistence',async()=>{
  const root=await fs.mkdtemp(path.join(os.tmpdir(),'rpg-http-'));
  const media=path.join(root,'media');await fs.mkdir(path.join(media,'Tormenta','Fichas'),{recursive:true});
  const pdf=await PDFDocument.create();const page=pdf.addPage();pdf.getForm().createTextField('Nome').addToPage(page,{x:40,y:500,width:200,height:30});
  const bytes=await pdf.save();
  for(const name of ['Tormenta/Fichas/Modelo.pdf','Tormenta/Modulo.pdf','Tormenta/Outro.pdf'])await fs.writeFile(path.join(media,name),bytes);
  const socket=net.createServer();await new Promise<void>(resolve=>socket.listen(0,'127.0.0.1',resolve));const port=(socket.address() as net.AddressInfo).port;await new Promise<void>(resolve=>socket.close(()=>resolve()));
  const server=spawn(process.execPath,['dist/server/index.js'],{env:{...process.env,PORT:String(port),DB_FILE:path.join(root,'db'),DATA_FILE:path.join(root,'json'),CACHE_DIR:path.join(root,'cache'),LIBRARY_CACHE_DB_FILE:path.join(root,'library.db'),MEDIA_ROOT:media,VAULT_MEDIA_ROOT:path.join(root,'vault'),SESSION_SECRET:'test-rpg-only',PUGOTILAB_PROFILE_URL:'http://127.0.0.1:1'},stdio:['ignore','pipe','pipe']});
  let logs='';server.stderr.on('data',data=>logs+=data);
  const base=`http://127.0.0.1:${port}`;
  const request=(url:string,cookie='',body?:unknown,method=body===undefined?'GET':'POST')=>fetch(base+url,{method,headers:{Cookie:cookie,'Content-Type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});
  const json=async(response:Response,status=200)=>{const data=await response.json() as any;assert.equal(response.status,status,JSON.stringify(data));return data;};
  try{
    let ready=false;
    for(let i=0;i<300;i++){if(await fetch(base+'/health').then(r=>r.ok).catch(()=>false)){ready=true;break;}await new Promise(resolve=>setTimeout(resolve,100));}
    assert.ok(ready,logs);
    const setup=await request('/api/setup/admin','',{username:'admin',displayName:'Admin',email:'admin@example.com',password:'test-password-123'});assert.equal(setup.status,201);const admin=setup.headers.get('set-cookie')!.split(';')[0];
    const library=(await json(await request('/api/libraries',admin,{name:'RPG',kind:'other',path:media}),201)).library;
    const id=(filename:string)=>`${library.id}:${Buffer.from(filename).toString('base64url')}`;
    const endpoint=(contentId:string,suffix='rpg')=>`/api/contents/${encodeURIComponent(contentId)}/${suffix}`;
    const template=id('Tormenta/Fichas/Modelo.pdf'),module=id('Tormenta/Modulo.pdf'),other=id('Tormenta/Outro.pdf');
    const sessions:Record<string,string>={},users:Record<string,string>={};
    for(const name of ['sekiro','ivis','viewer']){
      await json(await request('/api/admin/users',admin,{username:name,displayName:name,email:name+'@example.com',password:'test-password-123',role:'user',allowedLibraryIds:[library.id]}),201);
      const login=await request('/api/login','',{username:name,password:'test-password-123'});assert.equal(login.status,200);sessions[name]=login.headers.get('set-cookie')!.split(';')[0];users[name]=(await json(await request('/api/me',sessions[name]))).user.id;
    }
    const patch=(contentId:string,body:unknown,cookie=admin)=>request(endpoint(contentId),cookie,body,'PATCH');
    assert.equal((await patch(template,{role:'template'},sessions.sekiro)).status,403);
    await json(await patch(template,{role:'template'}));
    const templateDoc=(await json(await request(endpoint(template),admin))).document;
    for(const contentId of [module,other])await json(await patch(contentId,{role:'module',templateIds:[templateDoc.id]}));
    const moduleDoc=(await json(await request(endpoint(module),admin))).document;
    const otherDoc=(await json(await request(endpoint(other),admin))).document;
    assert.equal((await json(await request(endpoint(template),sessions.sekiro))).modules.length,2);
    assert.equal((await patch(module,{role:'module',templateIds:['invalid']})).status,400);
    assert.equal((await json(await request(endpoint(module),admin))).templates.length,1,'invalid request preserves links');
    const schema=await json(await request(endpoint(template,'pdf-form'),sessions.sekiro));assert.equal(schema.saveCreatesCopy,true);
    const created=await json(await request(endpoint(template,'pdf-form/save'),sessions.sekiro,{name:'Mephisto',values:{Nome:'Sekiro'},revision:schema.revision,moduleId:moduleDoc.id}),201);
    const sheet=created.content.id;
    assert.deepEqual(await fs.readFile(path.join(media,'Tormenta/Fichas/Modelo.pdf')),Buffer.from(bytes));
    assert.equal((await request(endpoint(template,'pdf-form/rename'),admin,{name:'Changed',revision:schema.revision})).status,403);
    let details=await json(await request(endpoint(module),sessions.sekiro));assert.equal(details.mySheets[0].id,sheet);
    assert.equal((await json(await request(endpoint(module),sessions.ivis))).mySheets.length,0);
    for(const suffix of ['rpg','pdf-form','pages/0','cover'])assert.equal((await request(endpoint(sheet,suffix),sessions.ivis)).status,404);
    const listing=await json(await request(`/api/libraries/${library.id}/contents`,sessions.ivis));assert.ok(!listing.contents.some((item:any)=>item.id===sheet));
    await json(await patch(sheet,{visibility:'shared',sharedWithUserIds:[users.ivis]},sessions.sekiro));
    const readonly=await json(await request(endpoint(sheet,'pdf-form'),sessions.ivis));assert.equal(readonly.canEdit,false);
    assert.equal((await request(endpoint(sheet,'pages/0'),sessions.ivis)).status,200);
    for(const action of ['save','rename','preview','copies'])assert.equal((await request(endpoint(sheet,'pdf-form/'+action),sessions.ivis,{revision:readonly.revision,values:{Nome:'Intruso'}})).status,403);
    assert.equal((await patch(sheet,{visibility:'public'},sessions.ivis)).status,403);
    assert.equal((await request(endpoint(sheet,'pdf-form'),sessions.viewer)).status,404);
    details=await json(await request(endpoint(module),sessions.ivis));assert.equal(details.sharedSheets[0].id,sheet);
    const count=(await fs.readdir(path.join(media,'Tormenta/Fichas'))).filter(name=>name.endsWith('.pdf')).length;
    const saved=await json(await request(endpoint(sheet,'pdf-form/save'),sessions.sekiro,{revision:readonly.revision,values:{Nome:'Mephisto atualizado'}}));assert.equal(saved.content.id,sheet);
    assert.equal((await fs.readdir(path.join(media,'Tormenta/Fichas'))).filter(name=>name.endsWith('.pdf')).length,count);
    const duplicate=await json(await request(endpoint(sheet,'pdf-form/copies'),sessions.sekiro,{name:'Duplicata',values:{},revision:saved.revision}),201);
    const duplicateInfo=await json(await request(endpoint(duplicate.content.id),sessions.sekiro));assert.equal(duplicateInfo.copy.moduleId,moduleDoc.id);assert.equal(duplicateInfo.copy.visibility,'private');
    assert.equal((await request(endpoint(duplicate.content.id),sessions.ivis)).status,404);
    assert.equal((await patch(sheet,{moduleId:'missing'},admin)).status,400);
    await json(await patch(sheet,{moduleId:otherDoc.id},admin));
    assert.equal((await json(await request(endpoint(other),sessions.sekiro))).mySheets[0].id,sheet);
    const moduleSchema=await json(await request(endpoint(other,'pdf-form'),admin));
    const renamed=await json(await request(endpoint(other,'pdf-form/rename'),admin,{name:'Outro renomeado',revision:moduleSchema.revision}));
    assert.equal((await json(await request(endpoint(renamed.content.id),admin))).document.id,otherDoc.id);
    assert.equal((await json(await request(endpoint(sheet),sessions.sekiro))).modules[0].id,renamed.content.id);
    assert.equal((await patch(renamed.content.id,{role:null},admin)).status,400,'cannot orphan linked sheets');
    // Filesystem renames are reconciled before serving pages, including direct URLs.
    await fs.rename(path.join(media,duplicate.filename),path.join(media,'Tormenta/Fichas/Movida.pdf'));
    const moved=id('Tormenta/Fichas/Movida.pdf');
    assert.equal((await request(endpoint(moved,'pages/0'),sessions.ivis)).status,404);
    const movedInfo=await json(await request(endpoint(moved),sessions.sekiro));assert.equal(movedInfo.copy.moduleId,moduleDoc.id);
    // Same-inode aliases must not bypass the private-sheet check.
    await fs.link(path.join(media,'Tormenta/Fichas/Movida.pdf'),path.join(media,'Tormenta/Fichas/Alias.pdf'));
    assert.equal((await request(endpoint(id('Tormenta/Fichas/Alias.pdf'),'pages/0'),sessions.ivis)).status,404);
    await json(await patch(sheet,{ownerUserId:users.ivis,visibility:'private',sharedWithUserIds:[]},admin));
    assert.equal((await request(endpoint(sheet),sessions.sekiro)).status,404);
    assert.equal((await json(await request(endpoint(sheet,'pdf-form'),sessions.ivis))).canEdit,true);
    await fs.writeFile(path.join(media,'Ficha existente.pdf'),bytes);
    const existing=id('Ficha existente.pdf');
    assert.equal((await patch(existing,{role:'sheet',ownerUserId:users.sekiro},sessions.sekiro)).status,403);
    assert.equal((await patch(existing,{role:'sheet',ownerUserId:'missing'})).status,400);
    await json(await patch(existing,{role:'sheet',ownerUserId:users.sekiro,moduleId:moduleDoc.id}));
    assert.equal((await request(endpoint(existing,'pages/0'),sessions.ivis)).status,404);
    const existingDetails=await json(await request(endpoint(existing),sessions.sekiro));
    assert.equal(existingDetails.copy.ownerUserId,users.sekiro);
    assert.equal(existingDetails.copy.moduleId,moduleDoc.id);
    assert.deepEqual(await fs.readFile(path.join(media,'Ficha existente.pdf')),Buffer.from(bytes));
    const outside=await json(await request(endpoint(existing,'pdf-form/copies'),sessions.sekiro,{name:'Copia organizada',values:{}}),201);
    assert.equal(outside.filename,'Fichas/Copia organizada.pdf');
    await fs.mkdir(path.join(media,'Tormenta','Fichas','Grupo'));
    await fs.rename(path.join(media,'Tormenta/Fichas/Movida.pdf'),path.join(media,'Tormenta/Fichas/Grupo/Movida.pdf'));
    await fs.unlink(path.join(media,'Tormenta/Fichas/Alias.pdf'));
    const reorganized=await json(await request(endpoint(id('Tormenta/Fichas/Grupo/Movida.pdf')),sessions.sekiro));
    assert.equal(reorganized.copy.system,'Tormenta/Fichas/Grupo');
    const sharedModule=await fetch(base+'/shared/rpg-folders.js');
    assert.equal(sharedModule.status,200);
    assert.match(await sharedModule.text(),/RPG_SHEETS_FOLDER/);
    assert.deepEqual(await fs.readFile(path.join(media,'Tormenta/Fichas/Modelo.pdf')),Buffer.from(bytes));
  }finally{server.kill();await new Promise(resolve=>server.once('exit',resolve));await fs.rm(root,{recursive:true,force:true});}
});
